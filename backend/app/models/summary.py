import uuid
from datetime import datetime, timezone
from sqlalchemy import Column, String, Integer, DateTime, ForeignKey, Text, JSON, Boolean
from sqlalchemy.orm import relationship
from app.core.database import Base

class DocumentSummary(Base):
    __tablename__ = "document_summaries"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    document_id = Column(String(36), ForeignKey("medical_documents.id", ondelete="CASCADE"), unique=True, nullable=False)
    user_id = Column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    
    quick_summary = Column(Text, nullable=False)
    key_findings = Column(JSON, default=list) # List[str]
    lab_values = Column(JSON, default=list) # List[dict: name, value, unit, reference_range, status]
    recommendations = Column(JSON, default=list) # List[str]
    questions_for_doctor = Column(JSON, default=list) # List[str]
    citations = Column(JSON, default=list) # List[dict: quote, page_number]
    disclaimer = Column(Text, default="This summary is generated by AI for informational purposes only. It is not medical advice, diagnosis, or treatment. Please consult a qualified healthcare provider for clinical decisions.")
    language = Column(String(10), default="en")
    is_ai_generated = Column(Boolean, default=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))
    updated_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), onupdate=lambda: datetime.now(timezone.utc))

    document = relationship("MedicalDocument", back_populates="summary")
